const assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const { createEpisodePanelController } = require('./episode-panel');
const area = { x: 0, y: 0, width: 1440, height: 900 };
const main = new EventEmitter();
main.webContents = new EventEmitter(); main.webContents.mainFrame = {};
main.isDestroyed = () => false;
let bounds = { x: 200, y: 30, width: 620, height: 850 };
let top = false;
main.getBounds = () => ({ ...bounds });
main.setBounds = value => { bounds = value; };
main.getMinimumSize = () => [420, 560];
main.setAlwaysOnTop = value => { top = value; };
main.isAlwaysOnTop = () => top;
const handlers = {};
const ipcMain = { handle: (name, fn) => { handlers[name] = fn; }, on() {} };
let layout = 'portrait';
const controller = createEpisodePanelController({ ipcMain, screen: { getDisplayMatching: () => ({ workArea: area }) }, getMainWindow: () => main, getLayout: () => layout });
controller.attach(main);
const event = { sender: main.webContents, senderFrame: main.webContents.mainFrame };
const toggle = value => handlers['set-episode-panel-open'](event, value);
assert.equal(toggle(true), 200);
assert.deepEqual(bounds, { x: 200, y: 30, width: 820, height: 850 });
assert.equal(toggle(true), 200);
assert.equal(bounds.width, 820);
assert.equal(toggle(false), 0);
assert.deepEqual(bounds, { x: 200, y: 30, width: 620, height: 850 });
bounds.x = 820;
toggle(true);
assert.equal(bounds.x, 620);
toggle(false);
assert.equal(bounds.x, 820);
toggle(true); bounds.width += 50; toggle(false);
assert.equal(bounds.width, 670);
area.width = 700; bounds = { x: 0, y: 30, width: 620, height: 850 };
assert.equal(toggle(true), 80);
assert.equal(bounds.width, 700);
main.webContents.emit('did-start-loading');
assert.equal(bounds.width, 620);
assert.throws(() => handlers['set-episode-panel-open']({ sender: {}, senderFrame: {} }, true));
assert.throws(() => handlers['set-always-on-top']({ sender: {}, senderFrame: {} }, true));
assert.throws(() => toggle('yes'));
assert.equal(handlers['set-always-on-top'](event, true), true);
assert.equal(handlers['get-always-on-top'](event), true);
assert.equal(handlers['set-always-on-top'](event, false), false);
layout = 'landscape';
assert.throws(() => toggle(true));
console.log('episode dock: expansion, restore, manual resize, edges, repeat, reload, permissions and pin passed');
